import { env } from '../config/env';

interface SendOtpEmailOptions {
  email: string;
  otp: string;
  name?: string;
}

/**
 * Sends a transactional 6-digit OTP email to a citizen using the Brevo (formerly Sendinblue) REST API.
 */
export async function sendOtpEmail({ email, otp, name }: SendOtpEmailOptions): Promise<{ success: boolean; messageId?: string }> {
  const recipientName = name?.trim() || 'Citizen';

  const htmlContent = `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>CivicConnect Email Verification</title>
  <style>
    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif;
      margin: 0;
      padding: 0;
      background-color: #f1f5f9;
      color: #0f172a;
    }
    .container {
      max-width: 560px;
      margin: 30px auto;
      background: #ffffff;
      border: 1px solid #cbd5e1;
      border-radius: 8px;
      overflow: hidden;
      box-shadow: 0 4px 6px -1px rgba(0, 0, 0, 0.1);
    }
    .tricolor {
      height: 4px;
      width: 100%;
      background: linear-gradient(to right, #FF9933 33.33%, #FFFFFF 33.33%, #FFFFFF 66.66%, #138808 66.66%);
    }
    .header {
      background-color: #0a2540;
      padding: 24px 30px;
      text-align: left;
      border-bottom: 2px solid #1e3a8a;
    }
    .header h1 {
      margin: 0;
      font-size: 20px;
      color: #ffffff;
      font-weight: 800;
      letter-spacing: 0.5px;
    }
    .header p {
      margin: 4px 0 0 0;
      font-size: 12px;
      color: #93c5fd;
      text-transform: uppercase;
      letter-spacing: 1px;
    }
    .content {
      padding: 30px;
    }
    .greeting {
      font-size: 15px;
      font-weight: 600;
      color: #1e293b;
      margin-bottom: 12px;
    }
    .message {
      font-size: 14px;
      line-height: 1.6;
      color: #334155;
      margin-bottom: 24px;
    }
    .otp-card {
      background-color: #f8fafc;
      border: 2px dashed #0284c7;
      border-radius: 8px;
      padding: 20px;
      text-align: center;
      margin: 24px 0;
    }
    .otp-label {
      font-size: 11px;
      text-transform: uppercase;
      letter-spacing: 1.5px;
      color: #64748b;
      font-weight: 700;
      margin-bottom: 8px;
    }
    .otp-code {
      font-family: 'Courier New', Courier, monospace;
      font-size: 34px;
      font-weight: 900;
      letter-spacing: 8px;
      color: #0369a1;
      margin: 0;
      padding-left: 8px;
    }
    .expiry-note {
      font-size: 12px;
      color: #dc2626;
      font-weight: 600;
      margin-top: 8px;
    }
    .security-notice {
      background-color: #fffbeb;
      border-left: 4px solid #f59e0b;
      padding: 12px 16px;
      font-size: 12px;
      color: #92400e;
      border-radius: 4px;
      margin-bottom: 24px;
      line-height: 1.5;
    }
    .footer {
      background-color: #f8fafc;
      border-top: 1px solid #e2e8f0;
      padding: 20px 30px;
      font-size: 11px;
      color: #64748b;
      line-height: 1.5;
      text-align: center;
    }
    .footer strong {
      color: #334155;
    }
  </style>
</head>
<body>
  <div class="container">
    <div class="tricolor"></div>
    <div class="header">
      <h1>CIVICCONNECT</h1>
      <p>Citizen Services & Societal Innovation Portal</p>
    </div>
    
    <div class="content">
      <div class="greeting">Dear ${recipientName},</div>
      <div class="message">
        Thank you for initiating Citizen registration on the CivicConnect municipal grievance resolution network. Please use the One-Time Password (OTP) below to verify your email address.
      </div>
      
      <div class="otp-card">
        <div class="otp-label">Security Verification Code</div>
        <div class="otp-code">${otp}</div>
        <div class="expiry-note">⏳ Valid for 5 minutes (single-use only)</div>
      </div>
      
      <div class="security-notice">
        <strong>Security Notice:</strong> Never share this verification OTP with anyone, including civic officials or support personnel. If you did not request this verification, please disregard this email.
      </div>
      
      <div class="message" style="margin-bottom: 0;">
        Regards,<br>
        <strong>CivicConnect Municipal Administration & Public Grievance Team</strong>
      </div>
    </div>
    
    <div class="footer">
      This is an automated institutional notification generated by the CivicConnect Portal.<br>
      Please do not reply directly to this email.
    </div>
  </div>
</body>
</html>
  `;

  // Check if Brevo API Key is configured
  if (!env.BREVO_API_KEY) {
    console.warn(`⚠️ [Brevo Service Notice] BREVO_API_KEY is not configured in .env.`);
    console.log(`🔑 [Local Dev OTP] Verification OTP for ${email}: ${otp}`);
    return { success: true, messageId: 'dev-mock-id' };
  }

  try {
    const response = await fetch('https://api.brevo.com/v3/smtp/email', {
      method: 'POST',
      headers: {
        'api-key': env.BREVO_API_KEY,
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
      body: JSON.stringify({
        sender: {
          name: env.BREVO_SENDER_NAME || 'CivicConnect',
          email: env.BREVO_SENDER_EMAIL || 'noreply@civicconnect.gov.in',
        },
        to: [
          {
            email: email.trim().toLowerCase(),
            name: recipientName,
          },
        ],
        subject: 'CivicConnect Email Verification OTP',
        htmlContent,
      }),
    });

    const data = (await response.json()) as any;

    if (!response.ok) {
      const errorMessage = data?.message || data?.error || 'Failed to dispatch email via Brevo transactional service.';
      console.error('❌ Brevo API Error:', { status: response.status, data });
      throw new Error(`Brevo Email Delivery Failed: ${errorMessage}`);
    }

    return {
      success: true,
      messageId: data.messageId,
    };
  } catch (error: any) {
    console.error('❌ Error sending OTP email via Brevo:', error);
    throw error;
  }
}
